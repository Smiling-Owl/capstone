import assert from 'node:assert/strict';
import { readFile, readdir } from 'node:fs/promises';
import { createWorkbenchApi } from './workbench-api.mjs';

const version = { id: 'v1', name: 'Defense draft', published_at: '2026-09-28T00:00:00Z' };
const snapshot = { format: 1, erd: { entities: [], relationships: [] }, rdmDbml: 'Table sample { id int [pk] }', postgres: { text: 'create table sample(id int);' }, targets: [{ type: 'table', id: 'sample' }] };
const calls = [];
const fakeFetch = async (url, options) => {
  calls.push({ url, options });
  let data;
  if (url.includes('/auth/v1/token?grant_type=password')) data = { access_token: 'access', refresh_token: 'refresh', expires_in: 3600, user: { id: 'u1' } };
  else if (url.includes('/auth/v1/token?grant_type=refresh_token')) data = { access_token: 'new-access', refresh_token: 'new-refresh', expires_in: 3600, user: { id: 'u1' } };
  else if (url.includes('/workbench_memberships?')) data = [{ user_id: 'u1', email: 'panel@example.edu', role: 'panelist', active: true }];
  else if (url.includes('/workbench_schema_versions?select=id,name,published_at,snapshot')) data = [{ ...version, snapshot }];
  else if (url.includes('/workbench_schema_versions?')) data = [version];
  else if (url.includes('/rpc/publish_workbench_schema_version')) data = 'v2';
  else if (url.includes('/workbench_annotations?')) data = [];
  else data = { ok: true };
  return { ok: true, status: 200, json: async () => data };
};
const api = createWorkbenchApi({ url: 'https://example.supabase.co', anonKey: 'anon-only' }, fakeFetch);
const session = await api.signIn('panel@example.edu', 'password');
assert.equal(session.expires_at > Math.floor(Date.now() / 1000), true, 'expiry is derived from expires_in');
assert.equal((await api.membership()).role, 'panelist');
assert.equal((await api.versions())[0].id, 'v1');
assert.equal((await api.snapshot('v1')).snapshot.targets[0].id, 'sample');
await api.annotations('v1', 'table', 'sample');
await api.createAnnotation({ schema_version_id: 'v1', target_type: 'table', target_id: 'sample', content: 'Check this relation.' });
assert.equal(calls.slice(1, 5).every(call => call.options.headers.Authorization === 'Bearer access'), true, 'authenticated requests carry the session');
assert.equal((await api.refresh('refresh')).access_token, 'new-access');
assert.equal(api.session.refresh_token, 'new-refresh');
api.setSession({ ...api.session, expires_at: 0 });
await api.versions();
assert.equal(api.session.access_token, 'new-access', 'expiring sessions refresh before protected requests');
assert.equal(calls.at(-1).options.headers.Authorization, 'Bearer new-access');
await api.publish('v2', snapshot);
assert.equal(calls.at(-1).url.endsWith('/rpc/publish_workbench_schema_version'), true);

const migration = await readFile(new URL('./supabase/migrations/202609280001_schema_workbench_review.sql', import.meta.url), 'utf8');
assert.match(migration, /alter table public\.workbench_invitations enable row level security;[\s\S]*?alter table public\.workbench_invitations force row level security;/);
assert.match(migration, /create policy workbench_schema_publish[\s\S]*?created_by = auth\.uid\(\) and private\.workbench_role\(\) = 'owner'/);
assert.match(migration, /workbench_annotation_edit_own[\s\S]*?private\.workbench_role\(\) in \('owner', 'panelist'\)/);
assert.match(migration, /create function private\.workbench_role\(\)/);
assert.doesNotMatch(migration, /create function public\.workbench_role/);
assert.match(migration, /new\.email_confirmed_at is null then return new/);
assert.match(migration, /after insert or update of email_confirmed_at on auth\.users/);
assert.match(migration, /resolution attribution changes only with a status transition/);
assert.match(migration, /snapshot->'erd'->'entities'[\s\S]*?snapshot->'rdmDbml'[\s\S]*?snapshot->'rdmModules'[\s\S]*?snapshot->'postgres'->'text'/);
const inviteFunction = await readFile(new URL('./supabase/functions/workbench-invite/index.ts', import.meta.url), 'utf8');
assert.match(inviteFunction, /body\.action === 'resend'/);
assert.doesNotMatch(inviteFunction, /workbench_invitations'\)\.delete/);
const appSource = await readFile(new URL('./workbench-app.js', import.meta.url), 'utf8');
assert.match(appSource, /if \(!versions\.length\) \{ emptyVersionsScreen\(\); return; \}/, 'empty versions route to a role-aware first-run screen');
assert.match(appSource, /membership\.role !== 'owner'[\s\S]*?Schema not published yet[\s\S]*?return;/, 'panelists get a read-only unpublished state');
assert.match(appSource, /first-publish-form[\s\S]*?api\.publish\(form\.elements\.name\.value\.trim\(\), snapshot\)[\s\S]*?await startApp\(\)/, 'owners can publish the initial snapshot and enter the workbench');

const distFiles = await readdir(new URL('./dist/', import.meta.url));
assert.ok(distFiles.includes('index.html'));
for (const forbidden of ['erd-source-data.js', 'postgres-schema-source.js', 'schema-version.json']) assert.ok(!distFiles.includes(forbidden), `${forbidden} is excluded from the public build`);
const deployed = (await Promise.all(distFiles.filter(file => file.endsWith('.js') || file.endsWith('.html')).map(file => readFile(new URL(`./dist/${file}`, import.meta.url), 'utf8')))).join('\n');
assert.doesNotMatch(deployed, /SUPABASE_SERVICE_ROLE_KEY|Hazard_assessment_date_time|situation_report_response_action/);
console.log('Workbench cloud smoke checks passed (auth, expiry/refresh, member/version snapshots, annotation create, publish route, invitation confirmation/resend, RLS guardrails, sanitized build).');
